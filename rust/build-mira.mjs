// Builds MiRa for the browser: rust/mira-web → packages/mira/mira.js, one file
// with the WebAssembly inside, so a page needs only
//
//   <script src="https://cdn.jsdelivr.net/npm/@yuktishaalaa/mira" defer></script>
//
// Needs (once):
//   rustup target add wasm32-unknown-unknown
//   cargo install wasm-bindgen-cli --version 0.2.130 --locked
// Then: npm run build:mira
//
// packages/mira/mira.js is generated: commit it, never edit it by hand.

import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const crate = join(here, "mira-web")
const target = "wasm32-unknown-unknown"
const out = join(here, "..", "packages", "mira", "mira.js")
const version = JSON.parse(readFileSync(join(here, "..", "packages", "mira", "package.json"), "utf8")).version

// MIRA_BUILD_STD=1 builds Rust's std from source (only where the wasm32 target can't be installed).
const extra = process.env.MIRA_BUILD_STD ? ["-Z", "build-std=std,panic_abort"] : []
const env = process.env.MIRA_BUILD_STD ? { ...process.env, RUSTC_BOOTSTRAP: "1" } : process.env
try {
  execFileSync("cargo", ["build", "--release", "--target", target, ...extra], { cwd: crate, stdio: "inherit", env })
} catch {
  throw new Error(`Rust → WebAssembly failed. Install stable Rust from https://rustup.rs, then: rustup target add ${target}`)
}

const tmp = mkdtempSync(join(tmpdir(), "mira-"))
try {
  execFileSync("wasm-bindgen", [
    join(crate, "target", target, "release", "yuktai_mira_web.wasm"),
    "--target", "no-modules", "--no-typescript", "--out-dir", tmp, "--out-name", "mira",
  ], { stdio: "inherit" })
} catch {
  throw new Error("wasm-bindgen is missing: cargo install wasm-bindgen-cli --version 0.2.130 --locked")
}

// The glue works out the .wasm address from the script's URL. MiRa carries the
// .wasm inside, and that URL is invalid when mira.js is inlined or bundled
// (about:blank, srcdoc), so it must never stop the script.
const urlLine = "script_src = new URL(document.currentScript.src, location.href).toString();"
const rawGlue = readFileSync(join(tmp, "mira.js"), "utf8")
if (!rawGlue.includes(urlLine)) throw new Error("wasm-bindgen glue changed: check the script_src line in rust/build-mira.mjs")
const glue = rawGlue.replace(urlLine, `try { ${urlLine} } catch (e) { /* inlined: the .wasm is inside */ }`)
const wasm = readFileSync(join(tmp, "mira_bg.wasm"))
rmSync(tmp, { recursive: true, force: true })

const js = `/*! MiRa ${version} · Telugu for every HTML element · GPL-3.0-only
 *  Named after Dr. Miriyala Ramakrishna (మిరా). Sandeep Miriyala · Yuktishaalaa AI Lab
 *  https://github.com/sandeep-miriyala/yuktai/tree/main/packages/mira
 *  GENERATED by rust/build-mira.mjs from rust/mira-web (Rust). Do not edit by hand.
 *  Fonts: free OFL Telugu fonts, files unchanged, Telugu letters only. Nothing is sent to Google. */
(function () {
"use strict";
${glue.replace(/^let wasm_bindgen;/m, "var wasm_bindgen;")}
var b = atob("${wasm.toString("base64")}");
var bytes = new Uint8Array(b.length);
for (var i = 0; i < b.length; i++) bytes[i] = b.charCodeAt(i);
wasm_bindgen.initSync({ module: bytes });
window.mira = {
  split: wasm_bindgen.split, count: wasm_bindgen.count, truncate: wasm_bindgen.truncate,
  html: wasm_bindgen.html, fonts: wasm_bindgen.fonts, refresh: wasm_bindgen.refresh, version: wasm_bindgen.version
};
})();
`
writeFileSync(out, js)
console.log(`MiRa ${version}: packages/mira/mira.js (${(js.length / 1024).toFixed(0)} KB, wasm ${(wasm.length / 1024).toFixed(0)} KB)`)
