// Bundles src/worker/worker.ts (backend + search + embedder + Comlink) into one
// ES module string, written to src/worker/workerSource.ts. The panel starts it
// from a blob: URL, so sites need no extra file. The WebAssembly module is not
// in here: the page sends it to the worker in init().
import { build } from "esbuild"
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const res = await build({
  entryPoints: [join(root, "src/worker/worker.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
  legalComments: "none",
})
const code = res.outputFiles[0].text
const out = `// GENERATED by scripts/build-worker.mjs from src/worker/worker.ts. Do not edit.
// Rebuild with: npm run build:worker
export const WORKER_SOURCE: string = ${JSON.stringify(code)}
`
writeFileSync(join(root, "src/worker/workerSource.ts"), out)
console.log(`worker: ${code.length} bytes → src/worker/workerSource.ts`)
